"""Generate src/lib/teamColors.ts from the teams table in data/nfl.db.

Usage:
    .venv/bin/python scripts/generate_team_colors.py

Colors are nflverse's brand colors. To tune a team by hand (e.g. a color that
disappears on a dark background), add it to OVERRIDES below and re-run, so the
change survives regeneration.
"""
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DB = ROOT / "data" / "nfl.db"
OUT = ROOT / "src" / "lib" / "teamColors.ts"

# abbreviation -> any of {"shell", "stripe", "accent"} to replace
OVERRIDES: dict[str, dict[str, str]] = {}


def main() -> None:
    with sqlite3.connect(DB) as conn:
        rows = conn.execute(
            "SELECT team_abbr, team_name, team_color, team_color2, team_color3 FROM teams ORDER BY team_abbr"
        ).fetchall()

    lines = [
        "// Generated by scripts/generate_team_colors.py from the nflverse teams table.",
        "// Don't edit by hand; add overrides in the script and re-run it.",
        "",
        "export interface TeamColors {",
        "  name: string;",
        "  shell: string; // main helmet color",
        "  stripe: string; // stripe and secondary color",
        "  accent: string; // third color, falls back to the stripe color",
        "}",
        "",
        "export const TEAM_COLORS: Record<string, TeamColors> = {",
    ]
    for abbr, name, c1, c2, c3 in rows:
        colors = {"shell": c1.upper(), "stripe": c2.upper(), "accent": (c3 or c2).upper()}
        colors.update(OVERRIDES.get(abbr, {}))
        lines.append(
            f'  {abbr}: {{ name: "{name}", shell: "{colors["shell"]}", '
            f'stripe: "{colors["stripe"]}", accent: "{colors["accent"]}" }},'
        )
    lines.append("};")
    lines.append("")

    OUT.write_text("\n".join(lines))
    print(f"Wrote {len(rows)} teams to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
